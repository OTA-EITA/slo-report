// Package rules generates Prometheus / VictoriaMetrics (vmalert) rule files
// with recording rules for the error ratio and multi-window burn rate alerts.
package rules

import (
	"bytes"
	"fmt"
	"sort"
	"strconv"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/OTA-EITA/slo-report/internal/burn"
	"github.com/OTA-EITA/slo-report/internal/spec"
)

// AlertName is the name of every generated alert; severity and window labels
// tell them apart so routing can be configured once.
const AlertName = "SLOErrorBudgetBurn"

// RecordName returns the recording rule name for an error ratio window.
func RecordName(w spec.Duration) string { return "slo:error_ratio:rate" + w.String() }

type ruleFile struct {
	Groups []group `yaml:"groups"`
}

type group struct {
	Name     string `yaml:"name"`
	Interval string `yaml:"interval,omitempty"`
	Rules    []rule `yaml:"rules"`
}

type rule struct {
	Record      string            `yaml:"record,omitempty"`
	Alert       string            `yaml:"alert,omitempty"`
	Expr        string            `yaml:"expr"`
	For         string            `yaml:"for,omitempty"`
	Labels      map[string]string `yaml:"labels,omitempty"`
	Annotations map[string]string `yaml:"annotations,omitempty"`
}

// Generate renders a rule file for every SLO in f.
func Generate(f spec.File, policies []burn.Policy) ([]byte, error) {
	var out ruleFile
	for _, s := range f.SLOs {
		out.Groups = append(out.Groups, generateSLO(s, policies))
	}
	var b bytes.Buffer
	b.WriteString("# Generated by slo-report. Do not edit by hand; edit the SLO file and regenerate.\n")
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(out); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

func generateSLO(s spec.SLO, policies []burn.Policy) group {
	window := time.Duration(s.Window)
	labels := map[string]string{"slo": s.Name, "service": s.Service}
	for k, v := range s.Labels {
		labels[k] = v
	}
	g := group{Name: "slo-" + s.Name}
	for _, w := range burn.Windows(policies, window) {
		g.Rules = append(g.Rules, rule{
			Record: RecordName(spec.Duration(w)),
			Expr:   s.ErrorRatioQuery(spec.Duration(w)),
			Labels: labels,
		})
	}
	sel := fmt.Sprintf(`{slo=%q}`, s.Name)
	budget := s.ErrorBudget()
	for _, p := range policies {
		if !p.Applies(window) {
			continue
		}
		factor := p.Factor(window)
		threshold := num(factor * budget)
		long, short := spec.Duration(p.Long), spec.Duration(p.Short)
		alertLabels := map[string]string{
			"severity":     p.Severity,
			"long_window":  long.String(),
			"short_window": short.String(),
		}
		for k, v := range labels {
			alertLabels[k] = v
		}
		annotations := map[string]string{
			"summary": fmt.Sprintf("%s is burning its error budget %sx too fast", s.Name, num(factor)),
			"description": fmt.Sprintf("Error ratio of %s is above %s over both %s and %s. At this rate %s%% of the %s error budget is spent within %s.",
				s.Name, threshold, long, short, num(p.Consumption*100), s.Window, long),
		}
		if s.RunbookURL != "" {
			annotations["runbook_url"] = s.RunbookURL
		}
		g.Rules = append(g.Rules, rule{
			Alert:       AlertName,
			Expr:        fmt.Sprintf("%s%s > %s\nand\n%s%s > %s", RecordName(long), sel, threshold, RecordName(short), sel, threshold),
			For:         spec.Duration(p.For).String(),
			Labels:      alertLabels,
			Annotations: annotations,
		})
	}
	return g
}

// num formats a float without trailing noise, e.g. 0.0144 rather than 0.014400000000000001.
func num(f float64) string {
	return strconv.FormatFloat(f, 'g', 6, 64)
}

// Names lists the alert labels each SLO produces, for documentation and tests.
func Names(rf []byte) ([]string, error) {
	var f ruleFile
	if err := yaml.Unmarshal(rf, &f); err != nil {
		return nil, err
	}
	var out []string
	for _, g := range f.Groups {
		for _, r := range g.Rules {
			if r.Alert != "" {
				out = append(out, g.Name+"/"+r.Labels["severity"]+"/"+r.Labels["long_window"])
			} else {
				out = append(out, g.Name+"/"+r.Record)
			}
		}
	}
	sort.Strings(out)
	return out, nil
}
